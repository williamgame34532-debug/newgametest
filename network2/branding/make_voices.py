# The voice lines: branding/voices (the phrase lists, the Russian texts) -> gamemode/core/sh_voices_data.lua.
# python3 branding/make_voices.py branding gamemode/core/sh_voices_data.lua
import json, os, re, sys
S = sys.argv[1]; OUT = sys.argv[2]
d = json.load(open(S + '/voices/voices_raw.json'))
tr = [l.rstrip('\n') for l in open(S + '/voices/tr_citizen.txt', encoding='utf-8')]
uniq = []
for g in ('male', 'female'):
    for k, t, p in d[g]:
        if t not in uniq: uniq.append(t)
assert len(uniq) == len(tr), (len(uniq), len(tr))
T = dict(zip(uniq, tr))
shipped = {'male': set(os.listdir(S + '/../content/sound/network2/voices/male01')), 'female': set(os.listdir(S + '/../content/sound/network2/voices/female01'))}

def norm(s):
    s = s.lower().replace('ё', 'е')
    s = ''.join(c if (('a' <= c <= 'z') or ('а' <= c <= 'я') or c.isdigit() or c == '-') else ' ' for c in s)
    return ' '.join(s.split())

def q(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

def sound(g, p):
    folder = 'male01' if g == 'male' else 'female01'
    name = p.rsplit('/', 1)[1]
    if p.startswith('vo/npc/' + folder + '/') and name in shipped[g]:
        return 'network2/voices/' + folder + '/' + name
    return p

lists = {}
for g in ('male', 'female'):
    lists['citizen_' + g] = [(norm(k), T[t], sound(g, p)) for k, t, p in d[g]]
cp, ota = [], []
for line in open(S + '/voices/cp_lines.txt', encoding='utf-8'):
    k, t, p = line.rstrip('\n').split('|')
    if 'combine_soldier' not in p:
        cp.append((norm(k), t, p))
# the Overwatch: its own list (soldier lines and some of Civil Protection)
for line in open(S + '/voices/ota_lines.txt', encoding='utf-8'):
    k, t, p = line.rstrip('\n').split('|')
    ota.append((norm(k), t, p))
lists['cp'] = cp; lists['ota'] = ota

out = ['-- The voice lines (sh_voices.lua): generated by branding/make_voices.py - {english key, russian text, sound}.',
       '-- The Russian key is the text itself (any case, without punctuation).', '',
       'NW.voices = NW.voices or {}', '', 'NW.voices.lists = {']
for name in ('citizen_male', 'citizen_female', 'cp', 'ota'):
    out.append('\t' + name + ' = {')
    for k, t, p in lists[name]:
        out.append('\t\t{' + q(k) + ', ' + q(t) + ', ' + q(p) + '},')
    out.append('\t},')
out.append('}')
open(OUT, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print({k: len(v) for k, v in lists.items()})
