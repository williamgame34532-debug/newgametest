NW.items.wardrobe = {}

for _, set in ipairs(WARDROBE) do
	for index, name in SortedPairs(set.names) do
		local id = "cl_" .. set.group .. "_" .. index

		NW.items.Register(id, {
			name = name,
			description = DESCRIPTIONS[set.group],
			category = "clothing",
			slot = set.slot,
			icon = set.icon,
			wear = {group = set.group, index = index},
			gasmask = set.gasmask and set.gasmask[index] or nil
		})

		NW.items.wardrobe[#NW.items.wardrobe + 1] = id
	end
end
