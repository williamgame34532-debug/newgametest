"""Generate lua/cf_rework/cl_partmap.lua: component signatures (raw MDL space) for each moving part.
Same component rule as the Lua runtime: triangles are joined when they share a vertex position
quantized to 1/100 unit; signature = triangle count + centroid of all triangle corners."""
import sys, json, math
sys.path.insert(0, '/tmp/bscripts')
import srcmdl
r = srcmdl.load('/tmp/u/fab/combine_fabricator/models/cf_rework/station.mdl')
V = r['verts']
P = json.load(open('/tmp/u/parts.json'))
TC = json.load(open('/tmp/u/tri_comp.json'))
q = lambda x: math.floor(x * 100 + 0.5)
tris = [t for m in r['meshes'] for t in m['tris']]
# recompute components with the exact runtime rule to be safe
parent = {}
def find(a):
    while parent[a] != a:
        parent[a] = parent[parent[a]]; a = parent[a]
    return a
keys = []
for t in tris:
    ks = [tuple(q(c) for c in V[i][0]) for i in t]
    for k in ks: parent.setdefault(k, k)
    for k in ks[1:]:
        a, b = find(ks[0]), find(k)
        if a != b: parent[b] = a
    keys.append(ks[0])
comp = {}
for ti, t in enumerate(tris):
    root = find(keys[ti])
    d = comp.setdefault(root, {'n': 0, 's': [0.0, 0.0, 0.0], 'tris': []})
    d['n'] += 1; d['tris'].append(ti)
    for i in t:
        for k in range(3): d['s'][k] += V[i][0][k]
# map old component ids (tri_comp) -> new roots via their first triangle
first = {}
for ti, cid in enumerate(TC):
    first.setdefault(cid, ti)
out = ['-- Generated by the offline model analysis: which pieces of station.mdl belong to which moving',
       '-- part. Each entry: triangle count, centroid x, y, z (raw MDL space, before the root yaw).',
       '-- The client splits the model into connected pieces with the same rule and matches them.',
       'CFRework = CFRework or {}', 'CFRework.PartMap = {']
total = 0
for name in ('cage', 'cells', 'rods', 'logo', 'lid'):
    ids = P[name]
    entries = []
    seen = set()
    for cid in ids:
        root = find(keys[first[cid]])
        if root in seen: continue
        seen.add(root)
        d = comp[root]
        n = d['n']; c = [d['s'][k] / (3 * n) for k in range(3)]
        entries.append('{%d,%.2f,%.2f,%.2f}' % (n, c[0], c[1], c[2]))
        total += n
    lines = []
    for i in range(0, len(entries), 6):
        lines.append('\t\t' + ','.join(entries[i:i + 6]) + ',')
    out.append('\t%s = {' % name)
    out.extend(lines)
    out.append('\t},')
out.append('}')
open('/home/user/newgametest/combine_fabricator/lua/cf_rework/cl_partmap.lua', 'w').write('\n'.join(out) + '\n')
print('tris in parts', total, 'components', len(comp))
