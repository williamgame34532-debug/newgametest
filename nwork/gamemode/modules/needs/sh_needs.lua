--[[-------------------------------------------------------------------------
	Нужды: сытость, жажда, бодрость (0..100).

	Сервер: NWORK.Needs.Get( ply, id ), NWORK.Needs.Add( ply, id, amount )
	Значения медленно падают, хранятся в data персонажа и передаются
	клиентам через NW2-переменные nwork_need_<id>.

	* на нуле сытости или жажды здоровье медленно падает (до 10);
	* при бодрости ниже 20 персонаж бегает медленнее;
	* бодрость восстанавливается, пока персонаж сидит на корточках
	  без движения (и от газировки).
---------------------------------------------------------------------------]]

MODULE.Name = "Нужды"
MODULE.Desc = "Голод, жажда и усталость."

NWORK.Needs = NWORK.Needs or {}
local N = NWORK.Needs

-- Time — секунд от 100 до 0
N.List = {
	{ id = "hunger", Time = 5400, Color = Color( 168, 150, 104 ), Glyph = "food",
	  Labels = { "Сыт", "Проголодался", "Голоден", "Истощён" },
	  Status = { [ 2 ] = "Вы проголодались.", [ 3 ] = "Вы голодны.", [ 4 ] = "Вы истощены от голода." } },
	{ id = "thirst", Time = 3600, Color = Color( 92, 128, 176 ), Glyph = "drop",
	  Labels = { "Напоен", "Хочет пить", "Жажда", "Обезвожен" },
	  Status = { [ 2 ] = "Вы хотите пить.", [ 3 ] = "Вас мучает жажда.", [ 4 ] = "Вы обезвожены." } },
	{ id = "rest",   Time = 7200, Color = Color( 88, 96, 168 ), Glyph = "sleep",
	  Labels = { "Бодр", "Утомлён", "Устал", "Измотан" },
	  Status = { [ 2 ] = "Вы немного утомлены.", [ 3 ] = "Вы чувствуете усталость.", [ 4 ] = "Вы валитесь с ног." } },
}

N.ById = {}
for _, n in ipairs( N.List ) do N.ById[ n.id ] = n end

function N.Get( ply, id )
	return ply:GetNW2Float( "nwork_need_" .. id, 100 )
end

-- ступень 1..4 по значению
function N.Stage( v )
	if v > 60 then return 1 elseif v > 30 then return 2 elseif v > 10 then return 3 end
	return 4
end
